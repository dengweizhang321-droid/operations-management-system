"""Explicit synthetic historical preconditions for real native lifecycle checks.

This does not claim that historical migration/cleanup actions were executed.
The final attestation is generated by the original validator from actual private
files and database snapshots. It is never substituted for signed Runner replies.
"""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import sqlite3
import sys
import uuid

spec=importlib.util.spec_from_file_location('bootstrap',Path(__file__).with_name('native-control-bootstrap.py'))
b=importlib.util.module_from_spec(spec);spec.loader.exec_module(b)
core=json.loads((b.RUNTIME/'secrets/credentials.dpapi.json').read_text())
os.environ.update(b.entry.environment())
os.environ.update(DJANGO_SETTINGS_MODULE='teruisi_backend.settings',TERUISI_DJANGO_ENVIRONMENT='test',
    TERUISI_DJANGO_DATABASE_URL='postgresql://postgres:'+b.plain(core['postgresSuperuser'])+'@127.0.0.1:25432/teruisi_sales',
    DJANGO_SECRET_KEY=b.plain(core['djangoSecretKey']),TERUISI_DJANGO_INTERNAL_SECRET=b.plain(core['internalSecret']))
import django
django.setup()
from django.apps import apps
from django.db import connection, transaction
from django.utils import timezone
from sales.models import ErpProductMaster, SalesDataRevision, SalesMigrationRun, SalesWriteAuthority
from sales.cutover_attestation import (_canonical_json, _read_d1_core_evidence, _target_snapshot,
    CLEANUP_MANIFEST_VERSION, record_d1_terminal_attestation, require_valid_cutover_attestation)
from sales.authority import prepare_write_authority, activate_write_authority
from sales.tests.test_cutover_attestation import create_terminal_d1
from erp_reference.import_service import SOURCE_LABELS, SOURCE_SCOPE_KEYS, combined_database_digest, content_hash, product_rows_from_database, combo_rows_from_database
from erp_reference.models import ErpReferenceImportBatch, ErpReferenceImportScopeHead

fixture=b.ROOT/'historical-bootstrap'
if fixture.exists():raise RuntimeError('Existing synthetic bootstrap retained; do not replay')
fixture.mkdir()
cutover='native-control-ai-20261108-sales'
source=fixture/'terminal.sqlite'
create_terminal_d1(source,cutover_id=cutover)
sha=lambda data:hashlib.sha256(data).hexdigest()
source_digest=sha(str(source.resolve()).encode())
source_file_sha=sha(source.read_bytes())
stamp=timezone.now()
authorities={}
synthetic=sha(b'native-control-ai-20261108: synthetic empty-domain bootstrap; no historical execution')
with connection.cursor() as cursor:
    cursor.execute('SHOW data_directory')
    assert Path(cursor.fetchone()[0]).resolve()==(b.RUNTIME/'postgres-data').resolve()

with transaction.atomic():
    ErpProductMaster.objects.create(product_code='NATIVE-ISOLATION-FIXTURE-ONLY',product_name='Synthetic native startup fixture',
        source_row_number=1,last_import_batch_id='native-bootstrap-products',created_at=stamp.isoformat(),updated_at=stamp.isoformat())
    for domain,model_name in [('sales','sales.SalesDataRevision'),('finance','finance.FinanceDataRevision'),
        ('netshop','netshop.NetshopDataRevision'),('market','market.MarketDataRevision'),('products','products.ProductDataRevision'),
        ('inventory','inventory.InventoryDataRevision'),('workflow','workflow.WorkflowDataRevision'),
        ('customer-service','customer_service.CustomerServiceDataRevision'),('access-control','access_control.AccessControlDataRevision'),
        ('ai-assistant','ai_assistant.AiDataRevision')]:
        apps.get_model(model_name).objects.update_or_create(domain=domain,defaults={'revision':1,'source_digest':synthetic})
    mapping={
        'finance':'finance.FinanceWriteAuthority','netshop':'netshop.NetshopWriteAuthority','market':'market.MarketWriteAuthority',
        'products':'products.ProductWriteAuthority','inventory':'inventory.InventoryWriteAuthority',
        'workflow':'workflow.WorkflowWriteAuthority','workflow-ops':'workflow.WorkflowOperationsWriteAuthority',
        'customer-service':'customer_service.CustomerServiceWriteAuthority','access-control':'access_control.AccessControlWriteAuthority',
        'erp-reference':'erp_reference.ErpReferenceWriteAuthority','ai-apply':'ai_assistant.AiWriteAuthority'}
    for name,model_name in mapping.items():
        model=apps.get_model(model_name)
        fields={f.name for f in model._meta.fields}
        values={'status':'postgres','authority_epoch':uuid.uuid4(),'cutover_id':'native-bootstrap-'+name,'activated_at':stamp}
        if 'migration_verify_run_id' in fields:values['migration_verify_run_id']=name+'-'+uuid.uuid4().hex
        model.objects.update_or_create(id=1,defaults=values)
        authorities[name]={k:str(v) for k,v in values.items()}
    for name,rows in [('products',product_rows_from_database()),('combos',combo_rows_from_database())]:
        digest=content_hash(name,rows)
        batch_id='native-bootstrap-'+name
        ErpReferenceImportBatch.objects.create(id=batch_id,source_key=name,source_label=SOURCE_LABELS[name],
            file_name='synthetic-'+name+'.json',file_size_bytes=len(_canonical_json(rows).encode()),file_hash=digest,raw_file_hash=digest,
            content_hash=digest,scope_key=SOURCE_SCOPE_KEYS[name],published_state_token=digest,sheet_name=name,status='completed',
            row_count=len(rows),inserted_count=len(rows),actor_email='native-fixture@example.invalid',completed_at=stamp)
        ErpReferenceImportScopeHead.objects.update_or_create(source_key=name,defaults={'scope_key':SOURCE_SCOPE_KEYS[name],
            'state_token':digest,'status':'ready','owner_token':'','current_batch_id':batch_id,'owner_started_at':None,'heartbeat_at':None})
    SalesDataRevision.objects.update_or_create(domain='erp',defaults={'revision':5,'source_digest':combined_database_digest()})
    SalesDataRevision.objects.update_or_create(domain='sales',defaults={'revision':8,'source_digest':synthetic})

    # Prior migration audit rows are explicitly synthetic bootstrap records;
    # all count/digest fields derive from this real private database snapshot.
    counts,digests=_target_snapshot()
    from sales.management.commands.migrate_sales_from_d1 import CANONICAL_FORMAT_VERSION, _domain_digest
    SalesDataRevision.objects.filter(domain='sales').update(source_digest=_domain_digest('sales',digests))
    SalesDataRevision.objects.filter(domain='erp').update(source_digest=_domain_digest('erp',digests))
    dry,applied,verified=[uuid.uuid4().hex for _ in range(3)]
    common=dict(source_fingerprint=source_file_sha,source_path_digest=source_digest,generation=uuid.uuid4().hex,
        source_revision='8:5',canonical_format_version=CANONICAL_FORMAT_VERSION,source_counts=counts,source_digests=digests,completed_at=stamp)
    SalesMigrationRun.objects.create(id=dry,status='dry_run_completed',dry_run=True,consumed_by_run_id=applied,approval_consumed_at=stamp,**common)
    SalesMigrationRun.objects.create(id=applied,status='completed',dry_run=False,approved_run_id=dry,target_revision='8:5',target_counts=counts,target_digests=digests,**common)
    SalesMigrationRun.objects.create(id=verified,status='verified',dry_run=False,target_revision='8:5',target_counts=counts,target_digests=digests,**common)
    authority=SalesWriteAuthority.objects.get(id=1)
    prepared=prepare_write_authority(expected_epoch=str(authority.authority_epoch),cutover_id=cutover)

sqlite=sqlite3.connect(source)
try: core_evidence=_read_d1_core_evidence(sqlite)
finally: sqlite.close()
identity=dict(version=CLEANUP_MANIFEST_VERSION,cutoverId=cutover,sourcePathDigest=source_digest,bucket='site-creator-r2',
    persistPathDigest=sha(str(fixture.resolve()).encode()),plannedAt=stamp.isoformat(),sessions=[],objects=[],coreEvidence=core_evidence)
cleanup={**identity,'manifestId':sha(_canonical_json(identity).encode()),'status':'completed','verifiedMissingObjectKeys':[],
    'lockedApplyRunId':applied,'lockedVerifyRunId':verified,'lockedVerifyRecordedAt':stamp.isoformat(),
    'metadataDeletedAt':stamp.isoformat(),'completedAt':stamp.isoformat()}
cleanup_path=fixture/'synthetic-empty-cleanup-precondition.json'
cleanup_path.write_text(json.dumps(cleanup,sort_keys=True,indent=2)+'\n',encoding='utf-8')
attestation=record_d1_terminal_attestation(source=source,cutover_id=cutover,migration_apply_run_id=applied,
    migration_verify_run_id=verified,cleanup_manifest=cleanup_path)
require_valid_cutover_attestation(cutover_id=cutover,verify_live_baseline=True)
activate_write_authority(expected_epoch=prepared['authorityEpoch'],cutover_id=cutover,attestation_sha256=attestation.payload_sha256)
# ERP's live scope digest evolves independently of its historical migration snapshot.
SalesDataRevision.objects.filter(domain='erp').update(source_digest=combined_database_digest())
from sales.runtime_guard import validate_erp_reference_runtime_state
validate_erp_reference_runtime_state()

from ai_assistant.control_models import AiMigrationRun
AiMigrationRun.objects.create(id=authorities['ai-apply']['migration_verify_run_id'],mode='apply',status='verified',
    source_path_digest=source_digest,source_snapshot_digest=synthetic,target_snapshot_digest=synthetic,
    manifest={'syntheticHistoricalPreconditions':True,'historicalMigrationExecuted':False},completed_at=stamp)
from bi.models import BiMigrationRun
bi=BiMigrationRun.objects.create(id='bi-apply-'+uuid.uuid4().hex,plan_id='native-bootstrap-'+uuid.uuid4().hex,status='verified',
    contract_version='bi-dashboard-read-model-v1',source_digest=synthetic,verified_at=stamp,
    source_snapshot_json={'syntheticHistoricalPreconditions':True})
result={'syntheticHistoricalPreconditions':True,'historicalMigrationExecuted':False,'cleanupDeletionExecuted':False,
    'emptyCleanupScopeVerified':True,'sourceFileSha256':source_file_sha,'attestationGeneratedByOriginalValidator':True,
    'attestationSha256':attestation.payload_sha256,'erpActualProductCount':1,'erpActualComboCount':0,
    'authorities':authorities,'bi':{'id':bi.id,'sourceDigest':bi.source_digest},'migrationFixtureIds':[dry,applied,verified]}
(b.EVIDENCE/'SYNTHETIC-PRECONDITIONS.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
print('Synthetic preconditions installed; original attestation and ERP runtime validation passed')
