for(const file of files)pins.push({path:file,sha256:hash(await readFile(file))});
const out=await open(root+'PRIMARY_FINAL_REGRESSION_V2.log','wx'),startedAt=new Date().toISOString();
const child=spawn(process.execPath,['--test','--test-reporter=tap',...files],{windowsHide:true,stdio:['ignore',out.fd,out.fd]});
const exitCode=await new Promise((res,rej)=>{child.once('error',rej);child.once('close',res);});await out.close();
for(const f of handoff.files)assert.equal(hash(await readFile(f.path)),f.sha256);
const finishedAt=new Date().toISOString(),text=await readFile(root+'PRIMARY_FINAL_REGRESSION_V2.log','utf8');
const count=Number(text.match(/# tests (\d+)/)?.[1]),passed=Number(text.match(/# pass (\d+)/)?.[1]),failed=Number(text.match(/# fail (\d+)/)?.[1]);
assert.ok(Number.isSafeInteger(count));
const record={status:exitCode===0&&failed===0?'passed':'failed',count,passed,failed,exitCode,startedAt,finishedAt,sourceHandoffSha256:hash(hraw),files:handoff.files,testFiles:pins,logSha256:hash(text),productionActions:0};
await writeFile(root+'PRIMARY_FINAL_REGRESSION.json',JSON.stringify(record,null,2)+'\n',{flag:'wx'});console.log(JSON.stringify({status:record.status,count,passed,failed}));process.exitCode=exitCode;
