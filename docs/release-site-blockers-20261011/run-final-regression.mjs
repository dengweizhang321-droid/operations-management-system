import {readFile,writeFile,open} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root='E:/codex-artifacts/release-site-blockers-20261011/',base=new URL('./',import.meta.url);
const names=['live-os-instance-policy.test.mjs','live-wsl-policy.test.mjs','live-wsl-host-policy.test.mjs','live-reference-audit.test.mjs','system-wsl-verifier.test.mjs','live-process-departure.test.mjs','live-guest-summary.test.mjs'];
