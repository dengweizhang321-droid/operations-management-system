import {readFile,writeFile,lstat} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root='E:/codex-artifacts/release-site-blockers-20261011/';
const sha=b=>createHash('sha256').update(b).digest('hex');
const raw=await readFile(root+'WSL_HOST_READONLY_PACKET_V2.json');
assert.equal(sha(raw),'6af6ec639f51242f3afc8290669fe83f9ea8a7cfab77794ceccead28445f67ad');
const packet=JSON.parse(raw),entry=await readFile(root+'RUN_READONLY_WSL_HOST_AUDIT_V2.cmd'),bootstrap=await readFile(root+'WSL_HOST_READONLY_BOOTSTRAP_V2.ps1');
const manifest=JSON.parse(await readFile(root+'WSL_HOST_READONLY_ENTRY_V2.json'));
assert.equal(sha(entry),manifest.entrySha256);assert.equal(sha(bootstrap),manifest.bootstrapSha256);
assert.equal(sha(await readFile(packet.script.path)),packet.script.sha256);assert.equal(sha(raw),manifest.packetSha256);
assert.equal(sha(await readFile(root+'ADMIN_RESIDUAL_METADATA_V2.json')),packet.baselineSha256);
const encoded=/ -EncodedCommand ([A-Za-z0-9+/=]+)\r?\n/.exec(entry.toString())[1];
assert.equal(Buffer.from(encoded,'base64').toString('utf16le'),bootstrap.toString('utf8'));
const ps='C:/Windows/System32/WindowsPowerShell/v1.0/powershell.exe';
const role=spawnSync(ps,['-NoProfile','-NonInteractive','-Command','([Security.Principal.WindowsPrincipal]::new([Security.Principal.WindowsIdentity]::GetCurrent())).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)'],{windowsHide:true,encoding:'utf8',timeout:10000});
assert.equal(role.status,0);assert.equal(role.stdout.trim(),'False','Do not run administrator capture as a test');
const result=spawnSync(ps,['-NoProfile','-NonInteractive','-EncodedCommand',encoded],{windowsHide:true,encoding:'utf8',timeout:10000,maxBuffer:128*1024});
assert.notEqual(result.status,0);assert.match(result.stderr,/Existing administrator PowerShell required/);
await assert.rejects(lstat(packet.outputPath),{code:'ENOENT'});
const record={packetSha256:sha(raw),entrySha256:sha(entry),scriptSha256:packet.script.sha256,exactEncodedSource:true,ordinaryRoleRefused:true,outputAbsent:true,nativeCaptureInvocations:0,productionActions:0};
await writeFile(root+'WSL_HOST_ENTRY_VERIFICATION_V2.json',JSON.stringify(record,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify(record));
